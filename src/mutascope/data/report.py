"""Write the cleaning report as Parquet (for code) and Markdown (for people).

The Markdown is rendered from the same validated table that goes to Parquet, so the two can
never disagree. It carries no timestamp or local path, so re-running on the same data gives a
byte-identical file and the diff shows only real count changes.
"""

from pathlib import Path

import duckdb
import pandas as pd

from mutascope.data.schemas import DROP_REASONS, CleaningReportSchema

REPORT_PARQUET = "cleaning_report.parquet"
REPORT_MARKDOWN = "cleaning_report.md"
_LABELS = {
    "assay_id": "assay_id",
    "rows_in": "rows in",
    "multi_mutant": "multi-mutant",
    "missing_value": "missing value",
    "duplicate": "duplicate",
    "conflicting_duplicate": "conflicting duplicate",
    "rows_out": "rows out",
}


def write_report(report: pd.DataFrame, report_dir: Path) -> tuple[Path, Path]:
    """Validate ``report`` and write ``cleaning_report.parquet`` and ``.md`` into ``report_dir``.

    Returns:
        The Parquet and Markdown paths.
    """
    report = CleaningReportSchema.validate(report, lazy=True)
    report_dir.mkdir(parents=True, exist_ok=True)
    parquet, markdown = report_dir / REPORT_PARQUET, report_dir / REPORT_MARKDOWN
    with duckdb.connect() as con:
        con.from_df(report).write_parquet(str(parquet))
    markdown.write_text(render_markdown(report))
    return parquet, markdown


def render_markdown(report: pd.DataFrame) -> str:
    """Human-readable summary: totals, the assays that need a look, then every assay."""
    reasons = ", ".join(f"`{r}`" for r in DROP_REASONS)
    lines = [
        "# Cleaning report",
        "",
        "Generated by `mutascope data clean` from the raw ProteinGym DMS substitution CSVs. "
        "Each row read is either written to the processed single-mutant table or removed for "
        f"exactly one reason, the first that applies, in this order: {reasons}. "
        "Rows with a wild-type mismatch or a malformed value are never removed: they fail the "
        "run instead.",
        "",
        "## Totals",
        "",
        "| | rows |",
        "|---|---:|",
        f"| assays | {len(report):,} |",
        f"| rows in | {int(report['rows_in'].sum()):,} |",
        *(f"| removed: {_LABELS[r]} | {int(report[r].sum()):,} |" for r in DROP_REASONS),
        f"| **rows out** | **{int(report['rows_out'].sum()):,}** |",
        "",
    ]

    other = [r for r in DROP_REASONS if r != "multi_mutant"]
    flagged = report[report[other].sum(axis=1) > 0]
    lines += ["## Assays with rows removed for reasons other than multi-mutants", ""]
    lines += _table(flagged) if len(flagged) else ["None.", ""]

    empty = report[report["rows_out"] == 0]
    lines += ["## Assays with no single mutants left", ""]
    lines += _table(empty) if len(empty) else ["None.", ""]

    lines += ["## Per assay", ""]
    lines += _table(report.sort_values("assay_id"))
    return "\n".join(lines)


def _table(df: pd.DataFrame) -> list[str]:
    columns = list(_LABELS)
    rows = [
        "| " + " | ".join(_LABELS[c] for c in columns) + " |",
        "|---|" + "---:|" * (len(columns) - 1),
    ]
    for record in df[columns].itertuples(index=False):
        assay_id, *numbers = record
        rows.append(f"| {assay_id} | " + " | ".join(f"{int(n):,}" for n in numbers) + " |")
    return [*rows, ""]
